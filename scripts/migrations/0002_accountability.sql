-- Keep source events, draft revisions, approvals and history immutable. User
-- deletion and explicit retention cleanup may still remove rows.
CREATE FUNCTION accountability_reject_history_update()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
    RAISE EXCEPTION 'Rows in % are immutable; insert a new revision or history row instead.', TG_TABLE_NAME
        USING ERRCODE = 'integrity_constraint_violation';
    RETURN NEW;
END;
$function$;

