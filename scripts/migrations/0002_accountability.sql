    WHERE provider_delivery_id IS NOT NULL;
CREATE INDEX accountability_reminder_deliveries_expiring_claim_idx
    ON accountability_reminder_deliveries (claim_expires_at)
    WHERE status = 'claimed';

CREATE TABLE accountability_check_ins (
    id UUID PRIMARY KEY,
    owner_id TEXT NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    local_date DATE NOT NULL,
    slot_id TEXT NOT NULL CHECK (slot_id ~ '^[a-z0-9][a-z0-9._:-]{0,63}$'),
    scheduled_local_time TIME NOT NULL,
    time_zone TEXT NOT NULL DEFAULT 'Asia/Kolkata' CHECK (time_zone = 'Asia/Kolkata'),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'answered', 'missed')),
    response_text TEXT CHECK (response_text IS NULL OR length(response_text) <= 4000),
    answered_at TIMESTAMPTZ,
    missed_at TIMESTAMPTZ,
    reminder_id UUID,
    reminder_delivery_id UUID,
    reminder_status TEXT NOT NULL DEFAULT 'not_scheduled'
        CHECK (reminder_status IN ('not_scheduled', 'scheduled', 'claimed', 'sent', 'failed', 'suppressed')),
    reminder_attempted_at TIMESTAMPTZ,
    reminder_sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT accountability_check_ins_owner_id_id_key UNIQUE (owner_id, id),
    CONSTRAINT accountability_check_ins_owner_date_slot_key UNIQUE (owner_id, local_date, slot_id),
    CONSTRAINT accountability_check_ins_status_shape_check CHECK (
        (status = 'pending' AND answered_at IS NULL AND missed_at IS NULL AND response_text IS NULL)
        OR (status = 'answered' AND answered_at IS NOT NULL AND missed_at IS NULL)
        OR (status = 'missed' AND answered_at IS NULL AND missed_at IS NOT NULL AND response_text IS NULL)
    ),
    CONSTRAINT accountability_check_ins_reminder_shape_check CHECK (
        (reminder_status = 'not_scheduled' AND reminder_delivery_id IS NULL
            AND reminder_attempted_at IS NULL AND reminder_sent_at IS NULL)
        OR (reminder_status = 'scheduled' AND reminder_id IS NOT NULL AND reminder_delivery_id IS NULL
            AND reminder_sent_at IS NULL)
        OR (reminder_status = 'claimed' AND reminder_id IS NOT NULL AND reminder_delivery_id IS NOT NULL
            AND reminder_sent_at IS NULL)
        OR (reminder_status = 'sent' AND reminder_id IS NOT NULL AND reminder_delivery_id IS NOT NULL
            AND reminder_attempted_at IS NOT NULL AND reminder_sent_at IS NOT NULL)
        OR (reminder_status = 'failed' AND reminder_id IS NOT NULL AND reminder_delivery_id IS NOT NULL
            AND reminder_attempted_at IS NOT NULL AND reminder_sent_at IS NULL)
        OR (reminder_status = 'suppressed' AND reminder_id IS NOT NULL AND reminder_sent_at IS NULL)
    ),
    CONSTRAINT accountability_check_ins_reminder_fk
        FOREIGN KEY (owner_id, reminder_id, slot_id)
        REFERENCES accountability_reminders (owner_id, id, slot_id)
        ON DELETE CASCADE,
    CONSTRAINT accountability_check_ins_delivery_fk
        FOREIGN KEY (owner_id, reminder_delivery_id, reminder_id, slot_id, local_date)
        REFERENCES accountability_reminder_deliveries (owner_id, id, reminder_id, slot_id, local_date)
        ON DELETE CASCADE
);

CREATE INDEX accountability_check_ins_owner_date_idx
    ON accountability_check_ins (owner_id, local_date DESC, scheduled_local_time);

CREATE TABLE accountability_weight_entries (
    id UUID PRIMARY KEY,
    owner_id TEXT NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    local_date DATE NOT NULL,
    measured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    original_value NUMERIC(8, 3) NOT NULL CHECK (original_value > 0),
    original_unit TEXT NOT NULL CHECK (original_unit IN ('kg', 'lb', 'st')),
    weight_kg NUMERIC(8, 3) GENERATED ALWAYS AS (
        CASE original_unit
            WHEN 'kg' THEN original_value
            WHEN 'lb' THEN ROUND(original_value * 0.45359237, 3)
            WHEN 'st' THEN ROUND(original_value * 6.35029318, 3)
        END
    ) STORED,
    notes TEXT CHECK (notes IS NULL OR length(notes) <= 2000),
    source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'imported', 'device', 'image')),
    confirmation_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (confirmation_status IN ('pending', 'confirmed', 'rejected')),
    confirmed_at TIMESTAMPTZ,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT accountability_weight_entries_owner_id_id_key UNIQUE (owner_id, id),
    CONSTRAINT accountability_weight_entries_normalized_range_check CHECK (weight_kg BETWEEN 0.001 AND 1000),
    CONSTRAINT accountability_weight_entries_confirmation_check CHECK (
        (confirmation_status = 'confirmed' AND confirmed_at IS NOT NULL)
        OR (confirmation_status <> 'confirmed' AND confirmed_at IS NULL)
    ),
    CONSTRAINT accountability_weight_entries_primary_confirmed_check CHECK (
        NOT is_primary OR confirmation_status = 'confirmed'
    )
);

CREATE UNIQUE INDEX accountability_weight_entries_primary_day_idx
    ON accountability_weight_entries (owner_id, local_date)
    WHERE is_primary AND confirmation_status = 'confirmed';
CREATE INDEX accountability_weight_entries_owner_date_idx
    ON accountability_weight_entries (owner_id, local_date DESC, measured_at DESC);

