    status TEXT NOT NULL CHECK (status IN ('claimed', 'sent', 'failed', 'suppressed')),
    claim_token UUID,
    claim_expires_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    attempted_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    error_code TEXT CHECK (error_code IS NULL OR error_code ~ '^[A-Z0-9_-]{1,64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT accountability_reminder_deliveries_owner_id_id_key UNIQUE (owner_id, id),
    CONSTRAINT accountability_reminder_deliveries_owner_ref_key
        UNIQUE (owner_id, id, reminder_id, slot_id, local_date),
    CONSTRAINT accountability_reminder_deliveries_owner_slot_date_key UNIQUE (owner_id, slot_id, local_date),
