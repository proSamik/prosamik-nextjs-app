CREATE UNIQUE INDEX accountability_idempotency_owner_operation_key_idx
    ON accountability_idempotency_keys (owner_id, operation_key, idempotency_key_hash);
CREATE INDEX accountability_idempotency_expiry_idx
    ON accountability_idempotency_keys (expires_at)
    WHERE expires_at IS NOT NULL;

