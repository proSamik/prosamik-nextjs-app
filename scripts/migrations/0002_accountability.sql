        OR (status = 'failed' AND sent_at IS NULL AND attempted_at IS NOT NULL AND attempt_count > 0)
        OR (status IN ('claimed', 'suppressed') AND sent_at IS NULL)
    ),
    CONSTRAINT accountability_reminder_deliveries_reminder_fk
        FOREIGN KEY (owner_id, reminder_id, slot_id)
        REFERENCES accountability_reminders (owner_id, id, slot_id)
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX accountability_reminder_deliveries_provider_id_idx
