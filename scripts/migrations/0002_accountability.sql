-- Private, owner-scoped accountability data. Every application query must still
-- authorize and filter by owner_id; composite foreign keys prevent cross-owner links.

CREATE TABLE accountability_habit_days (
    id UUID PRIMARY KEY,
    owner_id TEXT NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    habit_key TEXT NOT NULL CHECK (habit_key ~ '^[a-z0-9][a-z0-9._:-]{0,79}$'),
    local_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'unknown' CHECK (status IN ('complete', 'incomplete', 'unknown')),
    activity TEXT CHECK (activity IS NULL OR length(activity) <= 200),
    duration_minutes INTEGER CHECK (duration_minutes BETWEEN 0 AND 1440),
    outreach_count INTEGER CHECK (outreach_count BETWEEN 0 AND 999),
    outreach_channel TEXT CHECK (outreach_channel IN ('email', 'linkedin', 'phone', 'in_person', 'other')),
    email_drafted_count INTEGER NOT NULL DEFAULT 0 CHECK (email_drafted_count BETWEEN 0 AND 10000),
    email_sent_count INTEGER NOT NULL DEFAULT 0 CHECK (email_sent_count BETWEEN 0 AND 10000),
    video_stage TEXT CHECK (video_stage IN ('idea', 'planned', 'scripted', 'recorded', 'edited', 'published')),
    notes TEXT CHECK (notes IS NULL OR length(notes) <= 4000),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT accountability_habit_days_owner_id_id_key UNIQUE (owner_id, id),
    CONSTRAINT accountability_habit_days_owner_key_date_key UNIQUE (owner_id, habit_key, local_date),
    CONSTRAINT accountability_habit_days_outreach_requires_channel_check CHECK (
        outreach_count IS NULL OR outreach_count = 0 OR outreach_channel IS NOT NULL
    )
);

CREATE INDEX accountability_habit_days_owner_date_idx
    ON accountability_habit_days (owner_id, local_date DESC, habit_key);

CREATE TABLE accountability_idempotency_keys (
